"""
Diagnostics for link and image references.

The classes in this module track reference definitions and their usage while a
document is parsed. They do not alter the parser's behavior or its output in
any way; they only observe the events emitted by the parser's own reference
handling (see [`markdown.blockprocessors.ReferenceProcessor`][] and
[`markdown.inlinepatterns.ReferenceInlineProcessor`][]) so that the reported
diagnostics always reflect the parser's real reference label semantics,
including its label normalization rules. Content which the parser never treats
as a reference (code blocks and spans, backslash escapes, raw HTML, etc.)
is therefore never reported.

Three kinds of issues are reported:

* `unknown-reference`: a full (`[text][label]`), collapsed (`[text][]`) or
  shortcut (`[label]`) reference -- or the image variants thereof -- whose
  normalized label has no matching definition.
* `conflicting-definition`: a definition whose normalized label was already
  defined earlier in the same document.
* `unused-definition`: a definition whose normalized label is never
  referenced by the document.

Each diagnostic carries the normalized label and, when it can be located in
the original source, the 1-based line number. Content generated by extensions
(rather than read from the source document) cannot be located and is reported
with a `line` of `None` to indicate the source is unknown.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:  # pragma: no cover
    from markdown import Markdown

__all__ = [
    'UNKNOWN_REFERENCE',
    'CONFLICTING_DEFINITION',
    'UNUSED_DEFINITION',
    'ReferenceDiagnostic',
    'ReferenceDiagnosticsError',
    'ReferenceDiagnosticsCollector',
]

UNKNOWN_REFERENCE = 'unknown-reference'
""" Diagnostic kind for a reference with no matching definition. """

CONFLICTING_DEFINITION = 'conflicting-definition'
""" Diagnostic kind for a definition which conflicts with a previous definition. """

UNUSED_DEFINITION = 'unused-definition'
""" Diagnostic kind for a definition which is never referenced. """


class ReferenceDiagnostic:
    """
    A single diagnostic about a link or image reference.

    Attributes:
        kind (str): One of `unknown-reference`, `conflicting-definition` or
            `unused-definition`.
        label (str): The normalized reference label the diagnostic applies to.
        line (int | None): The 1-based line number in the original source, or
            `None` when the location is unknown (for example, content generated
            by an extension).
        message (str): A human-readable description of the issue.

    """

    def __init__(self, kind: str, label: str, line: int | None, message: str):
        self.kind = kind
        self.label = label
        self.line = line
        self.message = message

    def __repr__(self) -> str:
        return f"ReferenceDiagnostic({self.kind!r}, {self.label!r}, line={self.line!r})"

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, ReferenceDiagnostic):
            return NotImplemented
        return (
            self.kind == other.kind
            and self.label == other.label
            and self.line == other.line
            and self.message == other.message
        )


class ReferenceDiagnosticsError(Exception):
    """
    Raised by [`Markdown.convert`][markdown.Markdown.convert] when the
    `strict_references` option is enabled and reference diagnostics were found.

    The `diagnostics` attribute holds the list of
    [`ReferenceDiagnostic`][markdown.diagnostics.ReferenceDiagnostic] objects
    which caused the error.
    """

    def __init__(self, diagnostics: list[ReferenceDiagnostic]):
        self.diagnostics = diagnostics
        details = '; '.join(
            f"{d.kind} '{d.label}' ({'unknown source' if d.line is None else f'line {d.line}'})"
            for d in diagnostics
        )
        super().__init__(f'Reference diagnostics found: {details}')


class ReferenceDiagnosticsCollector:
    """
    Collects reference diagnostics for a [`Markdown`][markdown.Markdown] instance.

    The collector is notified by the parser's own reference handling each time
    a reference is defined or used, so normalization of labels always matches
    the parser. Line numbers are resolved afterwards by locating the already
    identified text in the original source; nothing is re-parsed here.
    """

    # Matches the start of a reference definition on a single source line.
    # Mirrors the label portion of `ReferenceProcessor.RE` so that located
    # lines are normalized with the exact same rule (`strip().lower()`).
    DEFINITION_START_RE = re.compile(r'^[ ]{0,3}\[([^\[\]]*)\]:')

    def __init__(self, md: Markdown):
        self.md = md
        self.reset()

    def reset(self) -> None:
        """ Clear all collected state to prepare for a new document. """
        self.diagnostics: list[ReferenceDiagnostic] = []
        self.definitions: dict[str, int | None] = {}
        self.used: set[str] = set()
        self._definition_cursor = 0
        self._reference_cursor = 0

    def record_definition(self, label: str) -> None:
        """
        Record a reference definition for the normalized `label`.

        Called by [`ReferenceProcessor`][markdown.blockprocessors.ReferenceProcessor]
        for every definition it accepts. A label which was already defined in
        the same document is reported as a `conflicting-definition`.
        """
        line = self._locate_definition(label)
        if label in self.definitions:
            previous = self.definitions[label]
            where = 'unknown source' if previous is None else f'line {previous}'
            self.diagnostics.append(ReferenceDiagnostic(
                CONFLICTING_DEFINITION,
                label,
                line,
                f"Reference '{label}' is defined more than once; first definition at {where}."
            ))
        else:
            self.definitions[label] = line

    def record_usage(self, label: str) -> None:
        """
        Record that the normalized `label` was used by a reference.

        Called by [`ReferenceInlineProcessor`][markdown.inlinepatterns.ReferenceInlineProcessor]
        when a reference successfully resolves to a definition.
        """
        self.used.add(label)

    def record_unknown(self, label: str, source_text: str) -> None:
        """
        Record a reference with no matching definition.

        Called by [`ReferenceInlineProcessor`][markdown.inlinepatterns.ReferenceInlineProcessor]
        with the normalized `label` and the exact source text of the reference.
        Duplicate reports of the same label at the same location are collapsed.
        """
        line = self._locate_text(source_text)
        diagnostic = ReferenceDiagnostic(
            UNKNOWN_REFERENCE,
            label,
            line,
            f"Reference '{label}' has no matching definition."
        )
        if diagnostic not in self.diagnostics:
            self.diagnostics.append(diagnostic)

    def get_diagnostics(self) -> list[ReferenceDiagnostic]:
        """
        Return all collected diagnostics, including unused definitions.

        Diagnostics are ordered by source line; entries which cannot be
        located in the source (such as extension-generated content) sort last.
        """
        diagnostics = list(self.diagnostics)
        for label, line in self.definitions.items():
            if label not in self.used:
                diagnostics.append(ReferenceDiagnostic(
                    UNUSED_DEFINITION,
                    label,
                    line,
                    f"Reference '{label}' is defined but never used."
                ))
        return sorted(diagnostics, key=lambda d: (d.line is None, d.line if d.line is not None else 0))

    def _locate_definition(self, label: str) -> int | None:
        """
        Return the 1-based line number of the definition of `label`.

        Definitions are recorded in document order, so a forward-only cursor
        over the original source lines finds each definition in turn. Returns
        `None` when the definition cannot be found in the source (for example,
        content generated by an extension).
        """
        lines = getattr(self.md, '_source_lines', None)
        if not lines:
            return None
        for index in range(self._definition_cursor, len(lines)):
            m = self.DEFINITION_START_RE.match(lines[index])
            if m and m.group(1).strip().lower() == label:
                self._definition_cursor = index + 1
                return index + 1
        return None

    def _locate_text(self, text: str) -> int | None:
        """
        Return the 1-based line number at which `text` occurs in the source.

        References are generally processed in document order, so a
        forward-only cursor is tried first, falling back to a search of the
        whole source. Returns `None` when the text cannot be found in the
        source (for example, content generated by an extension).
        """
        source = getattr(self.md, '_source_text', '')
        index = source.find(text, self._reference_cursor)
        if index == -1:
            index = source.find(text)
        if index == -1:
            return None
        self._reference_cursor = index + len(text)
        return source.count('\n', 0, index) + 1
